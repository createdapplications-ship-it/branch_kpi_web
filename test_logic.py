ok(f"Aug to same day {info['prev_total']:,.1f} = 15,692.6", abs(info["prev_total"] - 15692.6) < 0.05)
ok(f"MTD change {info['change_pct']:+.2%} = +17.15%", abs(info["change_pct"] - 0.1715) < 0.00005)
